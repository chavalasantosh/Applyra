-- Applyra real billing foundation (Razorpay-first).
-- Deploy after 001, 002 and 003.
-- No payment-provider secret is stored in Postgres or the browser. Razorpay credentials live
-- only in Supabase Edge Function secrets.

create table if not exists public.applyra_billing_plans (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  description text not null default '',
  provider text not null default 'razorpay' check (provider in ('razorpay')),
  provider_plan_id text not null unique,
  amount_subunits bigint not null check (amount_subunits >= 100),
  currency text not null default 'INR' check (currency ~ '^[A-Z]{3}$'),
  period text not null check (period in ('daily','weekly','monthly','quarterly','yearly')),
  interval integer not null default 1 check (interval >= 1 and interval <= 12),
  total_count integer not null default 12 check (total_count >= 1 and total_count <= 120),
  active boolean not null default true,
  entitlements jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.applyra_billing_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  plan_id uuid not null references public.applyra_billing_plans(id) on delete restrict,
  provider text not null default 'razorpay' check (provider in ('razorpay')),
  provider_subscription_id text not null unique,
  status text not null default 'created',
  checkout_url text not null default '',
  quantity integer not null default 1 check (quantity >= 1),
  current_start bigint not null default 0,
  current_end bigint not null default 0,
  ended_at bigint not null default 0,
  cancel_at_cycle_end boolean not null default false,
  last_provider_sync_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists applyra_billing_subscriptions_user_idx
  on public.applyra_billing_subscriptions(user_id, created_at desc);
create index if not exists applyra_billing_subscriptions_status_idx
  on public.applyra_billing_subscriptions(status, updated_at desc);
create unique index if not exists applyra_billing_one_open_subscription_per_user
  on public.applyra_billing_subscriptions(user_id)
  where status in ('created','authenticated','active','pending','halted','paused');

create table if not exists public.applyra_billing_checkout_locks (
  user_id uuid primary key references auth.users(id) on delete cascade,
  token uuid not null,
  locked_until timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.applyra_billing_events (
  id bigint generated by default as identity primary key,
  provider text not null default 'razorpay' check (provider in ('razorpay')),
  provider_event_id text not null unique,
  event_type text not null,
  provider_subscription_id text not null default '',
  provider_payment_id text not null default '',
  signature_verified boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.applyra_billing_plans enable row level security;
alter table public.applyra_billing_subscriptions enable row level security;
alter table public.applyra_billing_events enable row level security;
alter table public.applyra_billing_checkout_locks enable row level security;
alter table public.applyra_billing_plans force row level security;
alter table public.applyra_billing_subscriptions force row level security;
alter table public.applyra_billing_events force row level security;
alter table public.applyra_billing_checkout_locks force row level security;

-- Billing is intentionally API-mediated. The extension never talks directly to these tables.
revoke all on public.applyra_billing_plans from public, anon, authenticated;
revoke all on public.applyra_billing_subscriptions from public, anon, authenticated;
revoke all on public.applyra_billing_events from public, anon, authenticated;
revoke all on public.applyra_billing_checkout_locks from public, anon, authenticated;
revoke all on sequence public.applyra_billing_events_id_seq from public, anon, authenticated;

create or replace function public.applyra_acquire_billing_checkout_lock(p_user_id uuid, p_ttl_seconds integer default 120)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token uuid := gen_random_uuid();
  v_result uuid;
begin
  insert into public.applyra_billing_checkout_locks(user_id,token,locked_until,created_at)
  values(p_user_id,v_token,now() + make_interval(secs => greatest(30,least(coalesce(p_ttl_seconds,120),300))),now())
  on conflict(user_id) do update
    set token=excluded.token, locked_until=excluded.locked_until, created_at=now()
    where public.applyra_billing_checkout_locks.locked_until < now()
  returning token into v_result;
  return v_result;
end;
$$;

create or replace function public.applyra_release_billing_checkout_lock(p_user_id uuid, p_token uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare v_count integer;
begin
  delete from public.applyra_billing_checkout_locks where user_id=p_user_id and token=p_token;
  get diagnostics v_count = row_count;
  return v_count > 0;
end;
$$;

revoke execute on function public.applyra_acquire_billing_checkout_lock(uuid,integer) from public, anon, authenticated;
revoke execute on function public.applyra_release_billing_checkout_lock(uuid,uuid) from public, anon, authenticated;
grant execute on function public.applyra_acquire_billing_checkout_lock(uuid,integer) to service_role;
grant execute on function public.applyra_release_billing_checkout_lock(uuid,uuid) to service_role;

-- Admin summary helper. Edge Functions call this with the privileged server client only.
create or replace function public.applyra_billing_summary()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plans bigint := 0;
  v_active bigint := 0;
  v_pending bigint := 0;
  v_events_24h bigint := 0;
begin
  select count(*) into v_plans from public.applyra_billing_plans where active = true;
  select count(*) into v_active from public.applyra_billing_subscriptions where status in ('authenticated','active');
  select count(*) into v_pending from public.applyra_billing_subscriptions where status in ('created','pending','halted','paused');
  select count(*) into v_events_24h from public.applyra_billing_events where created_at >= now() - interval '24 hours';
  return jsonb_build_object(
    'plans_active',v_plans,
    'subscriptions_active',v_active,
    'subscriptions_attention',v_pending,
    'events_24h',v_events_24h,
    'generated_at',now()
  );
end;
$$;

revoke execute on function public.applyra_billing_summary() from public, anon, authenticated;
grant execute on function public.applyra_billing_summary() to service_role;
