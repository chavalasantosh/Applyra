create or replace function public.applyra_admin_summary()
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_users bigint := 0;
  v_active_24h bigint := 0;
  v_candidates bigint := 0;
  v_applications bigint := 0;
  v_admins bigint := 0;
  v_privacy_pending bigint := 0;
  v_errors_24h bigint := 0;
begin
  select count(*) into v_users from auth.users;
  select count(*) into v_active_24h from auth.users where last_sign_in_at >= now() - interval '24 hours';
  select count(*) into v_candidates from public.applyra_candidates;
  select count(*) into v_applications from public.applyra_applications;
  select count(*) into v_admins from public.applyra_admin_roles where active = true;
  select count(*) into v_privacy_pending from public.applyra_privacy_requests where status in ('requested','processing');
  select count(*) into v_errors_24h from public.applyra_admin_error_events where created_at >= now() - interval '24 hours';
  return jsonb_build_object(
    'users_total',v_users,
    'users_active_24h',v_active_24h,
    'candidates_total',v_candidates,
    'applications_total',v_applications,
    'admins_active',v_admins,
    'privacy_pending',v_privacy_pending,
    'errors_24h',v_errors_24h,
    'generated_at',now()
  );
end;
$$;

revoke execute on function public.applyra_admin_summary() from public, anon, authenticated;
grant execute on function public.applyra_admin_summary() to service_role;

