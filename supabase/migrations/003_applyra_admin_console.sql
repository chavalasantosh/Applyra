-- Applyra Admin Console foundation.
-- Deploy after migrations 001 and 002.
-- Admin tables are NOT exposed to normal authenticated users. The admin-api Edge Function
-- uses SUPABASE_SERVICE_ROLE_KEY server-side after verifying the caller's Supabase session
-- and active role in applyra_admin_roles.

create table if not exists public.applyra_admin_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('super_admin','admin','support','read_only')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.applyra_admin_config (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.applyra_admin_audit_events (
  id uuid primary key default gen_random_uuid(),
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  target_type text not null default '',
  target_id text not null default '',
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.applyra_privacy_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  request_type text not null check (request_type in ('export','delete','correct','other')),
  status text not null default 'requested' check (status in ('requested','processing','completed','failed','cancelled')),
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.applyra_admin_error_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  code text not null default '',
  feature text not null default '',
  message text not null default '',
  extension_version text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

